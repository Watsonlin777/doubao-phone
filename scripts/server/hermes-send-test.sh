#!/bin/bash
# Hermes 单次测试模板 —— 只含占位符和任务描述，没有真实账号、没有真实消息以外的示例
# 注意：单次运行（hermes -z）会按设计自动跳过审批，只用在你自己明确说的测试里
# 超时建议 1200 秒，不要设 600 秒（实测一趟接近 10 分钟，600 秒会被掐在输入完、没点发送那一步）
set -u

cd /root || exit 1
HOME=/root HERMES_HOME=/root/.hermes timeout 1200 hermes -z '用 phone_exec 和 phone-wechat-send skill，完成一次测试，只做这一次，不要重复发送。任务：打开微信，只打开文件传输助手这一个会话，发送前必须先读屏核对顶部标题确实是文件传输助手，标题不对就立刻停下，不要在别的会话里输入或发送。确认标题无误后，输入并发送恰好一条消息，内容是：你好。中文输入按 skill 走微信输入法拼音加空格的路，不要直接输中文，不要切百度输入法。整个过程按 skill 的阶段通知一节，每步开头先用 shell 发一条系统通知，标题是 Hermes 手机任务，标签是 hermes-phone-task，正文只写阶段，不要用 Termux 通知。发送后再次读屏，确认聊天里出现了一条新发出的你好，输入法已恢复回原始输入法，再结束并汇报是否成功、标题核对结果、阶段通知是否发出、以及发送后看到的新消息。整个任务只发一条消息，成功后不要再发第二条。'
